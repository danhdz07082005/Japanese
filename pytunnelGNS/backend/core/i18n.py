def normalize_lang(value: str | None) -> str:
    """Pick a supported language from a header/cookie value (e.g. 'en-US,en;q=0.9')."""
    for part in (value or "").lower().replace(" ", "").split(","):
        code = part.split(";")[0].split("-")[0]
        if code in MESSAGES:
            return code
    return DEFAULT_LANG


def t(lang: str, key: str, **params: Any) -> str:
    template = MESSAGES.get(lang, MESSAGES[DEFAULT_LANG]).get(key) or MESSAGES[DEFAULT_LANG].get(key, key)
    try:
        return template.format(**params)
    except (KeyError, IndexError):
        return template
